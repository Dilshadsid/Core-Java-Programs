
public class Demo_type_cashting {
	public static void main(String[] args) {// widening type casting
		// implicit conversion or casting down.
		int a = 100;
		long x = a;
		float z = x;
		double o = z;
		System.out.println(a);
		System.out.println(x);
		System.out.println(z);
		System.out.println(o);

	}
}
